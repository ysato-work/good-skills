test("CLI は例外の文面をそのまま出さず、失敗したことを簡潔に出す", () => {
  const script = fileURLToPath(new URL("./transcript-text.mjs", import.meta.url));
  const r = spawnSync(process.execPath, [script, "--file", "/nonexistent/x.jsonl"], { encoding: "utf8" });
  assert.equal(r.status, 2);
  assert.equal(r.stderr.trim(), "会話の記録の平文化に失敗しました");
  assert.ok(!r.stdout.includes("/nonexistent"));
  assert.ok(!r.stderr.includes("/nonexistent"));
});

test("CLI として起動すると --file の記録を平文にして出す", () => {
  const script = fileURLToPath(new URL("./transcript-text.mjs", import.meta.url));
  const { home, put } = fakeHome();
  const file = put("-w-cli", "abc");
  writeFileSync(file, line({ type: "user", timestamp: "t1", message: { content: "発言" } }));
  const out = execFileSync(process.execPath, [script, "--file", file], {
    encoding: "utf8",
    env: { ...process.env, CLAUDE_CONFIG_DIR: join(home, ".claude") },
  });
  assert.match(out, /<<<human t1>>>/);
});

