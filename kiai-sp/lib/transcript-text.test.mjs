test("開いた記述子の実体が置き場の外なら拒否する", () => {
  const { home } = fakeHome();
  const outside = mkdtempSync(join(tmpdir(), "tt-out-"));
  const secret = join(outside, "secret.jsonl");
  writeFileSync(secret, "秘密");
  const scope = join(home, ".claude", "projects");
  mkdirSync(scope, { recursive: true });
  const link = join(scope, "sneaky.jsonl");
  symlinkSync(secret, link);
  const root = mkdtempSync(join(tmpdir(), "tt-"));
  assert.throws(() => openVerified(root, link), /置き場/);
});

test("開いた記述子の実体が置き場の下なら、その記述子で読める", () => {
  const root = mkdtempSync(join(tmpdir(), "tt-"));
  const f = join(root, "abc.jsonl");
  writeFileSync(f, line({ type: "user", timestamp: "t1", message: { content: "発言" } }));
  const fd = openVerified(root, f);
  try {
    assert.match(readFileSync(fd, "utf8"), /発言/);
  } finally {
    closeSync(fd);
  }
});

// /proc が無い環境の経路。procFdDir に存在しない場所を渡すと、その経路を試せる
test("/proc が無い環境でも、置き場の下の記録を記述子で読める", () => {
  const root = mkdtempSync(join(tmpdir(), "tt-"));
  const f = join(root, "abc.jsonl");
  writeFileSync(f, line({ type: "user", timestamp: "t1", message: { content: "発言" } }));
  const fd = openVerified(root, f, { procFdDir: "/nonexistent-proc-self-fd" });
  try {
    assert.match(readFileSync(fd, "utf8"), /発言/);
  } finally {
    closeSync(fd);
  }
});

