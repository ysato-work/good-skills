test("置き場の下のハードリンクで、外の実体の記録は読めない", () => {
  const { home } = fakeHome();
  const outside = mkdtempSync(join(tmpdir(), "tt-out-"));
  const secret = join(outside, "secret.jsonl");
  writeFileSync(secret, line({ type: "user", timestamp: "t1", message: { content: "秘密" } }));
  const d = join(home, ".claude", "projects", "d");
  mkdirSync(d, { recursive: true });
  // 絶対パスの実体は置き場の下なので、リンク検査だけでは通る。リンク数で外の実
  // 体の別名だと見分ける
  const hard = join(d, "abc.jsonl");
  linkSync(secret, hard);
  assert.throws(() => resolveTranscriptPath({ file: hard, sessionId: null, home }), /--file/);
  assert.throws(() => run({ file: hard, home }), /--file/);
  assert.throws(() => resolveTranscriptPath({ sessionId: "abc", home }), /見つからない/);
  assert.throws(() => run({ sessionId: "abc", home }), /見つからない/);
});

