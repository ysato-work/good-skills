// 偽のホームを用意し、projects/<dir>/ に記録を置く。
// wakaranai と session-purge のテストが同じ形だが、プラグインをまたげないため写している。
const fakeHome = () => {
  const home = mkdtempSync(join(tmpdir(), "tt-"));
  const put = (dir, sessionId) => {
    const d = join(home, ".claude", "projects", dir);
    mkdirSync(d, { recursive: true });
    writeFileSync(join(d, `${sessionId}.jsonl`), "");
    return join(d, `${sessionId}.jsonl`);
  };
  return { home, put };
};

const line = (o) => JSON.stringify(o);

test("人間の発言だけを取り、AI の発言は取らない", () => {
  const file = [
    line({ type: "user", timestamp: "t1", message: { content: "スキル定義でもデッドコードがあったら消したい" } }),
    line({ type: "assistant", timestamp: "t2", message: { content: [{ type: "text", text: "了解しました" }] } }),
  ].join("\n");
  const got = humanMessages(file);
  assert.equal(got.length, 1);
  assert.equal(got[0].timestamp, "t1");
  assert.match(got[0].text, /デッドコード/);
});

test("機械が差し込んだ文は落とす", () => {
  const file = [
    line({ type: "user", timestamp: "t1", message: { content: "<system-reminder>rule</system-reminder>" } }),
    line({ type: "user", timestamp: "t2", message: { content: "<task-notification>x</task-notification>" } }),
    line({ type: "user", timestamp: "t3", message: { content: "これは人間の発言" } }),
  ].join("\n");
  const got = humanMessages(file);
  assert.equal(got.length, 1);
  assert.equal(got[0].text, "これは人間の発言");
});

